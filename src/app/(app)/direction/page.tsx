"use client";

import { useEffect, useRef, useState } from "react";
import { Plus, RefreshCw, SquarePen } from "lucide-react";
import { heading1Style } from "@/components/ui/TextField";
import SeriesEditModal from "@/components/SeriesEditModal";
import SeriesDetail from "@/components/SeriesDetail";
import SeriesSelection from "@/components/SeriesSelection";
import Link from "next/link";
import { highlightNav } from "@/lib/navHighlight";
import { api, ApiClientError, type ContentSeries, type SeriesSlotChange } from "@/lib/apiClient";
import { rhythmLabel } from "@/lib/seriesRhythm";
import { accent, accentAlpha, color } from "@/lib/design/tokens";
import { resolveCategoryMeta } from "@/lib/design/categoryDisplay";

function SeriesCard({
  series,
  selected,
  onSelect,
  onEdit,
}: {
  series: ContentSeries;
  selected: boolean;
  onSelect: () => void;
  onEdit: () => void;
}) {
  const meta = resolveCategoryMeta(series.category);

  return (
    <div
      onClick={onSelect}
      style={{
        background: color.cardBg,
        border: `${selected ? 1.5 : 1}px solid ${selected ? "oklch(0.6 0.15 292)" : color.border}`,
        boxShadow: selected ? `0 0 0 3px ${accentAlpha(0.08)}` : "none",
        borderRadius: 14,
        padding: 16,
        cursor: "pointer",
      }}
    >
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 8, marginBottom: 8 }}>
        <div style={{ fontWeight: 600, fontSize: 14, color: selected ? color.text : color.text2, minWidth: 0 }}>{series.label}</div>
        <div style={{ display: "flex", alignItems: "center", gap: 4, flexShrink: 0 }}>
          <span style={{ fontSize: 12, fontWeight: 600, color: series.rhythm ? color.textMuted : "oklch(0.55 0.18 60)" }}>
            {series.rhythm ? rhythmLabel(series.rhythm) : "No rhythm"}
          </span>
          <button
            onClick={(e) => {
              e.stopPropagation();
              onEdit();
            }}
            title="Edit this series"
            aria-label="Edit this series"
            style={{
              display: "grid",
              placeItems: "center",
              width: 26,
              height: 26,
              borderRadius: 8,
              border: "none",
              background: "none",
              color: color.textFaint,
              cursor: "pointer",
            }}
          >
            <SquarePen size={14} strokeWidth={2} />
          </button>
        </div>
      </div>

      <div style={{ display: "flex", gap: 6, flexWrap: "wrap", marginBottom: 10 }}>
        <span style={{ fontSize: 11, fontWeight: 600, color: meta.fg, background: meta.bg, borderRadius: 20, padding: "3px 9px" }}>
          {meta.label}
        </span>
      </div>

      <div style={{ fontSize: 12, color: color.textMuted }}>
        {series.readerLabel ? `For ${series.readerLabel}` : "Pick a reader in the series"}
      </div>
    </div>
  );
}

export default function DirectionPage() {
  const [series, setSeries] = useState<ContentSeries[]>([]);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [loaded, setLoaded] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<{ series: ContentSeries | null } | null>(null);
  // Arriving from onboarding (`?selection=1`): pick your series first, side by side, before
  // opening one (docs/SPEC_ONBOARDING_MVP.md).
  const [selectionMode, setSelectionMode] = useState(false);
  const [confirming, setConfirming] = useState(false);
  // Right after confirming: the calendar is filled, show the way.
  const [justPlanned, setJustPlanned] = useState(false);
  // Right after saving a series: where it filled in (docs/SPEC_RYTHME_DES_SERIES.md §4).
  const [slotNotice, setSlotNotice] = useState<(SeriesSlotChange & { label: string }) | null>(null);
  // 0 series is a legitimate AI result — this flag avoids re-running an LLM call on every mount.
  // Automatic generation only runs when leaving onboarding (`?selection=1`): elsewhere, 0 series
  // means the user removed them, and regenerating them unprompted would bring them back (seen
  // in real use on 2026-10-17).
  const hasAutoGenerated = useRef(false);

  function apply(next: ContentSeries[], removedId?: string) {
    setSeries(next);
    setSelectedId((current) => {
      if (current && current !== removedId && next.some((s) => s.id === current)) return current;
      return next[0]?.id ?? null;
    });
  }

  async function generate() {
    setGenerating(true);
    setError(null);
    try {
      const { series: generated } = await api.generateContentSeries();
      apply(generated);
    } catch (err) {
      setError(err instanceof ApiClientError ? err.message : "Couldn't generate series.");
    } finally {
      setGenerating(false);
    }
  }

  useEffect(() => {
    (async () => {
      const { series: loadedSeries } = await api.getContentSeries();
      apply(loadedSeries);
      const params = new URLSearchParams(window.location.search);
      // From the calendar ("Edit rhythm"): the open series, and its edit window.
      const target = loadedSeries.find((s) => s.id === params.get("series"));
      if (target) {
        setSelectedId(target.id);
        if (params.get("edit") === "1") setEditing({ series: target });
        window.history.replaceState(null, "", "/direction");
      }
      const fromOnboarding = params.get("selection") === "1";
      setSelectionMode(fromOnboarding && loadedSeries.length > 0);
      setLoaded(true);
      if (fromOnboarding && loadedSeries.length === 0 && !hasAutoGenerated.current) {
        hasAutoGenerated.current = true;
        await generate();
      }
    })();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function confirmSelection(keptIds: string[]) {
    setConfirming(true);
    setError(null);
    try {
      // The server spreads publishing days across the kept series and fills the calendar.
      const { plannedSeriesId, planError } = await api.confirmSeriesSelection(keptIds);
      const { series: refreshed } = await api.getContentSeries();
      setSeries(refreshed);
      setSelectedId(plannedSeriesId ?? refreshed[0]?.id ?? null);
      setSelectionMode(false);
      setJustPlanned(true);
      highlightNav("/calendar");
      window.history.replaceState(null, "", "/direction");
      if (planError) setError(planError);
    } catch (err) {
      setError(err instanceof ApiClientError ? err.message : "Couldn't confirm, please try again.");
    } finally {
      setConfirming(false);
    }
  }

  if (!loaded) return null;

  if (selectionMode) {
    return (
      <div style={{ padding: "32px 36px" }}>
        <h1 style={heading1Style}>Your series</h1>
        <p style={{ margin: "6px 0 22px", color: color.textMuted, fontSize: 15, maxWidth: 720 }}>
          Here are the recurring slots we suggest, drawn from what you&apos;re building. Uncheck the ones that
          don&apos;t feel like you, then confirm: your publishing days are spread across the ones you keep, and you can
          change each one&apos;s days afterwards.
        </p>
        {error && <p style={{ margin: "0 0 14px", fontSize: 13, color: color.danger }}>{error}</p>}
        <SeriesSelection series={series} busy={confirming} onConfirm={confirmSelection} />
      </div>
    );
  }

  const selected = series.find((s) => s.id === selectedId) ?? null;

  const sideButtonStyle: React.CSSProperties = {
    flex: 1,
    display: "flex",
    alignItems: "center",
    justifyContent: "center",
    gap: 7,
    fontFamily: "inherit",
    fontSize: 13,
    fontWeight: 600,
    color: color.textSecondary,
    background: color.cardBg,
    border: `1px solid ${color.inputBorder}`,
    borderRadius: 11,
    padding: "10px 12px",
    cursor: "pointer",
  };

  return (
    <div style={{ padding: "32px 36px" }}>
      <h1 style={heading1Style}>Direction</h1>
      <p style={{ margin: "6px 0 20px", color: color.textMuted, fontSize: 15 }}>
        Your series, and the story each one tells your audience — you steer it from here.
      </p>

      {error &&<p style={{ margin: "0 0 14px", fontSize: 13, color: color.danger }}>{error}</p>}

      {slotNotice && (
        <p style={{ margin: "0 0 14px", fontSize: 13, color: color.text2 }}>
          <strong>{slotNotice.label}</strong> :{" "}
          {slotNotice.created > 0
            ? `${slotNotice.created} post${slotNotice.created > 1 ? "s" : ""} added to the calendar through ${new Intl.DateTimeFormat("en-US", { month: "long", day: "numeric" }).format(new Date(`${slotNotice.until}T00:00:00`))}`
            : "calendar up to date"}
          {slotNotice.removed > 0 && `, ${slotNotice.removed} empty slot${slotNotice.removed > 1 ? "s" : ""} removed`}
          .{" "}
          <Link href="/calendar" style={{ color: accent, fontWeight: 600 }}>
            View the calendar →
          </Link>
        </p>
      )}

      {justPlanned && (
        <div
          style={{
            display: "flex",
            alignItems: "center",
            gap: 16,
            flexWrap: "wrap",
            margin: "0 0 20px",
            padding: "16px 18px",
            borderRadius: 14,
            background: accentAlpha(0.07),
            border: `1px solid ${accentAlpha(0.2)}`,
          }}
        >
          <span style={{ flex: 1, minWidth: 220, fontSize: 14, color: color.text2 }}>
            <strong style={{ color: color.text }}>Your first posts are scheduled.</strong> They&apos;re waiting on your
            publishing days: open the first one and Buildloud writes it.
          </span>
          <Link
            href="/calendar"
            style={{
              padding: "10px 18px",
              borderRadius: 11,
              background: accent,
              color: "#fff",
              fontWeight: 600,
              fontSize: 14,
              textDecoration: "none",
              boxShadow: `0 10px 24px -12px ${accent}`,
            }}
          >
            View my calendar →
          </Link>
        </div>
      )}

      <div style={{ display: "grid", gridTemplateColumns: "308px minmax(0, 1fr)", gap: 24, alignItems: "start" }}>
        <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
          <div
            style={{
              fontSize: 12,
              fontWeight: 700,
              color: color.textFaint,
              textTransform: "uppercase",
              letterSpacing: "0.05em",
              padding: "0 2px",
            }}
          >
            Series · {series.length}
          </div>

          {series.length === 0 && (
            <p style={{ margin: 0, fontSize: 13, color: color.textMuted, lineHeight: 1.5 }}>
              No series yet — your work may not need any, or you can add one manually.
            </p>
          )}

          {series.map((s) => (
            <SeriesCard
              key={s.id}
              series={s}
              selected={s.id === selectedId}
              onSelect={() => setSelectedId(s.id)}
              onEdit={() => setEditing({ series: s })}
            />
          ))}

          <div style={{ display: "flex", gap: 8, marginTop: 2 }}>
            <button onClick={() => setEditing({ series: null })} style={sideButtonStyle}>
              <Plus size={15} strokeWidth={2} />
              New series
            </button>
            <button onClick={generate} disabled={generating} style={{ ...sideButtonStyle, opacity: generating ? 0.6 : 1 }}>
              <RefreshCw size={15} strokeWidth={2} />
              {generating ? "..." : "Regenerate with AI"}
            </button>
          </div>
        </div>

        <div style={{ minWidth: 0 }}>
          {selected ? (
            <SeriesDetail
              key={selected.id}
              series={selected}
              onSeriesUpdate={(updated) => setSeries((prev) => prev.map((s) => (s.id === updated.id ? updated : s)))}
            />
          ) : (
            <div
              style={{
                background: color.cardBg,
                border: `1px solid ${color.border}`,
                borderRadius: 14,
                padding: "40px 24px",
                textAlign: "center",
                color: color.textMuted,
                fontSize: 14,
              }}
            >
              Select a series to see the story it tells.
            </div>
          )}
        </div>
      </div>

      {editing && (
        <SeriesEditModal
          // Remounts the form when switching from one series to another: the fields are
          // initialised from props, a simple prop change would not reset them.
          key={editing.series?.id ?? "new"}
          open
          series={editing.series}
          allSeries={series}
          onClose={() => setEditing(null)}
          onSaved={(saved, removedId, change) => {
            apply(saved, removedId);
            const label = change ? saved.find((s) => s.id === change.seriesId)?.label : undefined;
            setSlotNotice(change && label ? { ...change, label } : null);
          }}
        />
      )}
    </div>
  );
}
